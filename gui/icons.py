# Caché en memoria para no re-renderizar SVGs idénticos
_PIXMAP_CACHE: Dict[tuple, QPixmap] = {}
_ICON_CACHE: Dict[tuple, QIcon] = {}


def get_svg_pixmap(
    name: str,
    color: str = ICON_COLOR_DEFAULT,
    size: int = 16
) -> QPixmap:
    """
    Renderiza un icono SVG vectorial a QPixmap con la resolución y color deseados.
    """
    if QApplication.instance() is None:
        return QPixmap()

    cache_key = (name, color, size)
    if cache_key in _PIXMAP_CACHE:
        return _PIXMAP_CACHE[cache_key]

    raw_svg = SVG_REGISTRY.get(name)
    if not raw_svg:
        # Fallback a círculo genérico
        raw_svg = '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24"><circle cx="12" cy="12" r="8" fill="currentColor"/></svg>'

    svg_data = raw_svg.replace("currentColor", color)
    renderer = QSvgRenderer(QByteArray(svg_data.encode("utf-8")))

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.Antialiasing)
    painter.setRenderHint(QPainter.SmoothPixmapTransform)
    renderer.render(painter)
    painter.end()

    _PIXMAP_CACHE[cache_key] = pixmap
    return pixmap


def get_icon(
    name: str,
    color: str = ICON_COLOR_DEFAULT,
    hover_color: str = ICON_COLOR_HOVER,
    active_color: str = ICON_COLOR_ACTIVE,
    size: int = 16
) -> QIcon:
    """
    Crea un QIcon multi-estado a partir de un SVG para responder automáticamente
    a estados Normal, Hover y Activo en la interfaz Qt.
    """
    if QApplication.instance() is None:
        return QIcon()

    cache_key = (name, color, hover_color, active_color, size)
    if cache_key in _ICON_CACHE:
        return _ICON_CACHE[cache_key]

    pix_normal = get_svg_pixmap(name, color=color, size=size)
    pix_hover = get_svg_pixmap(name, color=hover_color, size=size)
    pix_active = get_svg_pixmap(name, color=active_color, size=size)
    pix_disabled = get_svg_pixmap(name, color=ICON_COLOR_MUTED, size=size)

    icon = QIcon()
    icon.addPixmap(pix_normal, QIcon.Normal, QIcon.Off)
    icon.addPixmap(pix_active, QIcon.Normal, QIcon.On)
    icon.addPixmap(pix_hover, QIcon.Active, QIcon.Off)
    icon.addPixmap(pix_hover, QIcon.Active, QIcon.On)
    icon.addPixmap(pix_disabled, QIcon.Disabled)

    _ICON_CACHE[cache_key] = icon
    return icon
